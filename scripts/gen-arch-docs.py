def mm_label(text: str) -> str:
    """Escape a string so it is safe inside a quoted Mermaid label."""
    text = str(text).replace("\n", " ").strip()
    return (
        text.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("#", "&num;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def mm_multiline(*parts: str) -> str:
    return "<br/>".join(mm_label(p) for p in parts if str(p).strip())


def mm_id(raw: str) -> str:
    """Turn arbitrary text into a stable, readable Mermaid-safe node id."""
    friendly = {OPEN_V4: "any_ipv4", OPEN_V6: "any_ipv6"}
    if str(raw) in friendly:
        return friendly[str(raw)]
    slug = re.sub(r"[^A-Za-z0-9_]", "_", str(raw)).strip("_")
    slug = re.sub(r"_{2,}", "_", slug)
    return slug if slug and slug[0].isalpha() else f"n_{slug}"


def network_diagram(model: Model) -> list[str]:
    """Topology grouped by tier, with route tables as first-class nodes.

    Routing decisions belong to a route table, not to a subnet, so drawing
    subnet -> route table -> target is both more accurate and far less noisy than
    fanning every subnet out to every gateway.
    """
    t = model.t
    lines = ["flowchart LR", '    internet(["Internet"])']

    vpc_id = model.vpcs[0] if model.vpcs else None
    if vpc_id:
        vpc_props = model.props(vpc_id)
        vpc_label = mm_multiline(
            f"VPC {model.name_of(vpc_id)}",
            f"IPv4 {t.render(vpc_props.get('CidrBlock'))}",
            "IPv6 Amazon-provided" if model.has_ipv6 else "",
        )
        lines.append(f'    subgraph {mm_id(vpc_id)}["{vpc_label}"]')
        lines.append("        direction LR")

    # --- subnets, grouped by tier ---
    tier_order = model._tier_order()
    by_tier: dict[str, list[dict]] = defaultdict(list)
    for subnet in model.subnets.values():
        by_tier[subnet["tier"]].append(subnet)
    for tier in sorted(by_tier, key=lambda x: tier_order.get(x, 99)):
        subnets = sorted(by_tier[tier], key=lambda s: (s["az"], s["name"]))
        lines.append(f'        subgraph tier_{mm_id(tier)}["{mm_label(tier)} tier"]')
        lines.append("            direction TB")
        for subnet in subnets:
            label = mm_multiline(subnet["name"], f'AZ {subnet["az"]}', subnet["cidr"])
            lines.append(f'            {mm_id(subnet["id"])}["{label}"]')
        lines.append("        end")

    # --- route tables ---
    if model.route_tables:
        lines.append('        subgraph routing["Route tables"]')
        lines.append("            direction TB")
        for rt_id in sorted(model.route_tables):
            has_default = any(
                r["destination"] in (OPEN_V4, OPEN_V6) for r in model.routes_for(rt_id)
            )
            label = mm_multiline(
                model.name_of(rt_id),
                "" if has_default else "no default route · isolated",
            )
            lines.append(f'            {mm_id(rt_id)}{{{{"{label}"}}}}')
        lines.append("        end")

    # --- gateways and endpoints ---
    gateway_types = {
        "AWS::EC2::InternetGateway": "internet gateway",
        "AWS::EC2::NatGateway": "NAT gateway",
        "AWS::EC2::EgressOnlyInternetGateway": "egress-only IGW",
        "AWS::EC2::TransitGatewayAttachment": "transit gateway attachment",
    }
    gateway_ids: list[str] = []
    endpoint_ids: list[str] = []
    lines.append('        subgraph edges_out["Gateways &amp; endpoints"]')
    lines.append("            direction TB")
    for rtype, human in gateway_types.items():
        for gid in model.by_type.get(rtype, []):
            gateway_ids.append(gid)
            extra = ""
            if rtype == "AWS::EC2::NatGateway":
                placed_in = sorted(t.refs_in(model.props(gid).get("SubnetId")))
                if placed_in and placed_in[0] in model.subnets:
                    extra = f'AZ {model.subnets[placed_in[0]]["az"]} only'
            lines.append(f'            {mm_id(gid)}[["{mm_multiline(model.name_of(gid), human, extra)}"]]')
    for endpoint in model.endpoints:
        endpoint_ids.append(endpoint["id"])
        label = mm_multiline(endpoint["service"], f'{endpoint["kind"]} endpoint', "IPv4 only"
                             if endpoint["kind"].lower() == "gateway" else "")
        lines.append(f'            {mm_id(endpoint["id"])}[/"{label}"/]')
    lines.append("        end")

    if vpc_id:
        lines.append("    end")

    # --- edges: subnet -> route table ---
    for subnet_id, rt in sorted(model.subnet_rt.items()):
        if subnet_id in model.subnets and rt in model.route_tables:
            lines.append(f"    {mm_id(subnet_id)} --> {mm_id(rt)}")

    # --- edges: route table -> target, labelled with the destination ---
    for rt_id in sorted(model.route_tables):
        for route in sorted(model.routes_for(rt_id), key=lambda r: (r["destination"], r["target"])):
            if not route["target"]:
                continue
            suffix = " (conditional)" if route["condition"] else ""
            lines.append(
                f'    {mm_id(rt_id)} -->|"{mm_label(route["destination"] + suffix)}"| {mm_id(route["target"])}'
            )
    for endpoint in model.endpoints:
        for rt in endpoint["route_tables"]:
            lines.append(f'    {mm_id(rt)} -->|"prefix list"| {mm_id(endpoint["id"])}')

    # --- edges: gateways -> internet ---
    igws = model.by_type.get("AWS::EC2::InternetGateway", [])
    for gid in igws:
        lines.append(f'    {mm_id(gid)} <-->|"ingress &amp; egress"| internet')
    for gid in model.by_type.get("AWS::EC2::NatGateway", []):
        if igws:
            lines.append(f'    {mm_id(gid)} -->|"source NAT"| {mm_id(igws[0])}')
    for gid in model.by_type.get("AWS::EC2::EgressOnlyInternetGateway", []):
        lines.append(f'    {mm_id(gid)} -->|"outbound IPv6 only"| internet')

    # --- styling ---
    lines.extend(
        [
            "    classDef publicTier fill:#fde68a,stroke:#b45309,color:#111827;",
            "    classDef appTier fill:#bfdbfe,stroke:#1d4ed8,color:#111827;",
            "    classDef dataTier fill:#fecaca,stroke:#b91c1c,color:#111827;",
            "    classDef rt fill:#ede9fe,stroke:#6d28d9,color:#111827;",
            "    classDef gw fill:#e5e7eb,stroke:#4b5563,color:#111827;",
            "    classDef ext fill:#f9fafb,stroke:#9ca3af,color:#374151,stroke-dasharray: 4 3;",
        ]
    )
    tier_class = {
        "public": "publicTier",
        "edge": "publicTier",
        "dmz": "publicTier",
        "application": "appTier",
        "app": "appTier",
        "private": "appTier",
        "data": "dataTier",
        "database": "dataTier",
    }
    by_class: dict[str, list[str]] = defaultdict(list)
    for subnet in model.subnets.values():
        by_class[tier_class.get(subnet["tier"], "gw")].append(mm_id(subnet["id"]))
    for rt_id in model.route_tables:
        by_class["rt"].append(mm_id(rt_id))
    for gid in gateway_ids + endpoint_ids:
        by_class["gw"].append(mm_id(gid))
    by_class["ext"].append("internet")
    for class_name, nodes in sorted(by_class.items()):
        if nodes:
            lines.append(f'    class {",".join(sorted(set(nodes)))} {class_name};')
    return lines


def security_diagram(model: Model) -> list[str]:
    if not model.security_groups:
        return []
    external: dict[str, str] = {}
    group_lines: list[str] = []
    edge_lines: list[str] = []

    for sg_id, sg in sorted(model.security_groups.items()):
        attached = model.sg_attachments.get(sg_id, [])
        attached_label = ", ".join(model.name_of(a) for a in attached[:3])
        if len(attached) > 3:
            attached_label += f", +{len(attached) - 3} more"
        label = mm_multiline(sg["name"], sg["description"], f"attached to: {attached_label}" if attached_label else "")
        group_lines.append(f'    {mm_id(sg_id)}["{label}"]')

    for sg_id, sg in sorted(model.security_groups.items()):
        for rule in sg["ingress"]:
            source = rule["source"]
            if not source:
                continue
            if rule["source_kind"] == "sg" and source in model.security_groups:
                src_node = mm_id(source)
            else:
                src_node = f"ext_{mm_id(source)}"
                open_to_world = source in (OPEN_V4, OPEN_V6)
                caption = "any host on the internet" if open_to_world else rule["source_kind"]
                external[src_node] = f'    {src_node}(["{mm_multiline(source, caption)}"])'
            edge_label = mm_label(f'{rule["protocol"]} {rule["ports"]}')
            edge_lines.append(f'    {src_node} -->|"{edge_label}"| {mm_id(sg_id)}')

    lines = ["flowchart LR"]
    lines += [external[key] for key in sorted(external)]
    lines += group_lines
    lines += edge_lines
    lines.append("    classDef ext fill:#f9fafb,stroke:#9ca3af,color:#374151,stroke-dasharray: 4 3;")
    if external:
        lines.append(f'    class {",".join(sorted(external))} ext;')
    return lines


def component_diagram(model: Model) -> list[str]:
    included = [
        logical_id
        for logical_id in sorted(model.t.resources)
        if model.type_of(logical_id) not in COMPONENT_EXCLUDE_TYPES
    ]
    if not included:
        return []
    included_set = set(included)
    lines = ["flowchart LR"]
    for logical_id in included:
        short_type = model.type_of(logical_id).replace("AWS::", "")
        conditional = model.condition_of(logical_id)
        label = mm_multiline(
            model.name_of(logical_id),
            short_type,
            f"only if {conditional}" if conditional else "",
        )
        shape_open, shape_close = ('[("', '")]') if model.type_of(logical_id) in STATEFUL_TYPES else ('["', '"]')
        lines.append(f"    {mm_id(logical_id)}{shape_open}{label}{shape_close}")

    for logical_id in included:
        for target in sorted(model.t.refs_in(model.body(logical_id))):
            if target in included_set and target != logical_id:
                lines.append(f"    {mm_id(logical_id)} --> {mm_id(target)}")

    conditional_nodes = [mm_id(r) for r in included if model.condition_of(r)]
    stateful_nodes = [mm_id(r) for r in included if model.type_of(r) in STATEFUL_TYPES]
    lines.append("    classDef stateful fill:#fecaca,stroke:#b91c1c,color:#111827;")
    lines.append("    classDef conditional stroke-dasharray: 5 3;")
    if stateful_nodes:
        lines.append(f'    class {",".join(sorted(set(stateful_nodes)))} stateful;')
    if conditional_nodes:
        lines.append(f'    class {",".join(sorted(set(conditional_nodes)))} conditional;')
    return lines


def lint_mermaid(block: Iterable[str], context: str) -> list[str]:
    """Cheap structural checks that catch the mistakes this generator could make."""
    problems: list[str] = []
    lines = list(block)
    depth = 0
    declared: set[str] = set()
    referenced: set[str] = set()

    for number, line in enumerate(lines, 1):
        stripped = line.strip()
        if stripped.startswith("subgraph "):
            depth += 1
            declared.add(stripped.split()[1].split("[")[0])
            continue
        if stripped == "end":
            depth -= 1
            if depth < 0:
                problems.append(f"{context}: unbalanced 'end' at line {number}")
            continue

        # An odd number of quotes means a label swallowed the rest of the line.
        if stripped.count('"') % 2:
            problems.append(f"{context}: unbalanced quotes at line {number}: {stripped}")

        # Node declaration: an id immediately followed by a shape opener.
        match = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*[\[({]", stripped)
        if match:
            declared.add(match.group(1))
        # Edges: collect both endpoints, ignoring any quoted edge label.
        without_labels = re.sub(r'\|"[^"]*"\|', " ", stripped)
        if re.search(r"[-.=]{1,2}[->.=]*>|<[-.=]", without_labels):
            for endpoint in re.findall(r"(?:^|\s)([A-Za-z_][A-Za-z0-9_]*)(?=\s|$|\[|\(|\{)", without_labels):
                referenced.add(endpoint)

    if depth != 0:
        problems.append(f"{context}: {depth} unclosed subgraph(s)")

    # Mermaid silently invents a node for an unknown id, which hides typos.
    keywords = {"flowchart", "TB", "LR", "TD", "RL", "BT", "direction", "class", "classDef", "end"}
    for node in sorted(referenced - declared - keywords):
        problems.append(f"{context}: edge references undeclared node '{node}'")
    return problems


