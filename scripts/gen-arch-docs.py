class Model:
    """Structured view of the template, derived generically from resource types."""

    def __init__(self, template: Template):
        self.t = template
        res = template.resources

        self.by_type: dict[str, list[str]] = defaultdict(list)
        for logical_id, body in sorted(res.items()):
            self.by_type[str((body or {}).get("Type", "unknown"))].append(logical_id)

        self.vpcs = self.by_type.get("AWS::EC2::VPC", [])
        self.has_ipv6 = bool(self.by_type.get("AWS::EC2::VPCCidrBlock"))

        self.subnets = {sid: self._subnet(sid) for sid in self.by_type.get("AWS::EC2::Subnet", [])}
        self.route_tables = {
            rid: self.name_of(rid) for rid in self.by_type.get("AWS::EC2::RouteTable", [])
        }

        # subnet -> route table, from explicit associations
        self.subnet_rt: dict[str, str] = {}
        for assoc_id in self.by_type.get("AWS::EC2::SubnetRouteTableAssociation", []):
            props = self.props(assoc_id)
            subnet_refs = self.t.refs_in(props.get("SubnetId"))
            rt_refs = self.t.refs_in(props.get("RouteTableId"))
            for subnet in subnet_refs:
                for rt in rt_refs:
                    self.subnet_rt[subnet] = rt

        self.routes = [self._route(rid) for rid in self.by_type.get("AWS::EC2::Route", [])]
        self.endpoints = [self._endpoint(eid) for eid in self.by_type.get("AWS::EC2::VPCEndpoint", [])]
        self.security_groups = {
            sg: self._security_group(sg) for sg in self.by_type.get("AWS::EC2::SecurityGroup", [])
        }
        self.sg_attachments = self._sg_attachments()
        self.listeners = [
            self._listener(lid)
            for lid in self.by_type.get("AWS::ElasticLoadBalancingV2::Listener", [])
        ]

    # -- small helpers ----------------------------------------------------- #

    def body(self, logical_id: str) -> dict:
        return self.t.resources.get(logical_id) or {}

    def props(self, logical_id: str) -> dict:
        return self.body(logical_id).get("Properties") or {}

    def type_of(self, logical_id: str) -> str:
        return str(self.body(logical_id).get("Type", "unknown"))

    def condition_of(self, logical_id: str) -> str | None:
        cond = self.body(logical_id).get("Condition")
        return str(cond) if cond else None

    def tags_of(self, logical_id: str) -> dict[str, str]:
        tags = self.props(logical_id).get("Tags")
        result: dict[str, str] = {}
        if isinstance(tags, list):
            for tag in tags:
                if isinstance(tag, dict) and "Key" in tag:
                    result[str(tag["Key"])] = self.t.render(tag.get("Value"))
        elif isinstance(tags, dict):
            for key, value in tags.items():
                result[str(key)] = self.t.render(value)
        return result

    def name_of(self, logical_id: str) -> str:
        """Prefer the Name tag, then an explicit name property, then the logical id."""
        tag_name = self.tags_of(logical_id).get("Name")
        if tag_name:
            return tag_name
        props = self.props(logical_id)
        for key in ("Name", "GroupName", "DBInstanceIdentifier", "AutoScalingGroupName",
                    "LaunchTemplateName", "LogGroupName", "DBSubnetGroupName"):
            if key not in props:
                continue
            value = props[key]
            # A name that is really a reference to another resource is not a name.
            if self.t.refs_in(value):
                continue
            return self.t.render(value)
        return logical_id

    # -- extraction -------------------------------------------------------- #

    def _subnet(self, logical_id: str) -> dict:
        props = self.props(logical_id)
        tags = self.tags_of(logical_id)
        index = self.t.az_index(props.get("AvailabilityZone"))
        return {
            "id": logical_id,
            "name": tags.get("Name", logical_id),
            "tier": tags.get("Tier", "untiered"),
            "cidr": self.t.render(props.get("CidrBlock")),
            "az": az_letter(index) if index is not None else self.t.render(props.get("AvailabilityZone")),
            "public_ip_on_launch": bool(props.get("MapPublicIpOnLaunch")),
        }

    def _route(self, logical_id: str) -> dict:
        props = self.props(logical_id)
        destination = ""
        for key in ("DestinationCidrBlock", "DestinationIpv6CidrBlock", "DestinationPrefixListId"):
            if key in props:
                destination = self.t.render(props[key])
                break
        target_id, target_kind = "", ""
        for key in ("GatewayId", "NatGatewayId", "EgressOnlyInternetGatewayId", "TransitGatewayId",
                    "VpcPeeringConnectionId", "NetworkInterfaceId", "InstanceId",
                    "CarrierGatewayId", "LocalGatewayId", "VpcEndpointId"):
            if key in props:
                refs = sorted(self.t.refs_in(props[key]))
                target_id = refs[0] if refs else self.t.render(props[key])
                target_kind = key
                break
        rt_refs = sorted(self.t.refs_in(props.get("RouteTableId")))
        return {
            "id": logical_id,
            "route_table": rt_refs[0] if rt_refs else "",
            "destination": destination,
            "target": target_id,
            "target_kind": target_kind,
            "condition": self.condition_of(logical_id),
        }

    def _endpoint(self, logical_id: str) -> dict:
        props = self.props(logical_id)
        return {
            "id": logical_id,
            "service": self.t.render(props.get("ServiceName")),
            "kind": self.t.render(props.get("VpcEndpointType")) or "Gateway",
            "route_tables": sorted(self.t.refs_in(props.get("RouteTableIds"))),
            "subnets": sorted(self.t.refs_in(props.get("SubnetIds"))),
        }

    def _security_group(self, logical_id: str) -> dict:
        props = self.props(logical_id)
        rules: list[dict] = []
        inline = props.get("SecurityGroupIngress")
        if isinstance(inline, list):
            rules.extend(self._ingress_rule(rule) for rule in inline)
        # Standalone ingress resources that target this group.
        for ingress_id in self.by_type.get("AWS::EC2::SecurityGroupIngress", []):
            ingress_props = self.props(ingress_id)
            if logical_id in self.t.refs_in(ingress_props.get("GroupId")):
                rules.append(self._ingress_rule(ingress_props))
        return {
            "id": logical_id,
            "name": self.tags_of(logical_id).get("Name", logical_id),
            "description": self.t.render(props.get("GroupDescription")),
            "ingress": rules,
            "egress_restricted": "SecurityGroupEgress" in props,
        }

    def _ingress_rule(self, rule: Any) -> dict:
        if not isinstance(rule, dict):
            return {"source": self.t.render(rule), "source_kind": "unknown", "ports": "", "description": ""}
        protocol = self.t.render(rule.get("IpProtocol"))
        from_port = rule.get("FromPort")
        to_port = rule.get("ToPort")
        if from_port is None and to_port is None:
            ports = "all"
        elif str(from_port) == str(to_port):
            ports = str(self.t.render(from_port))
        else:
            ports = f"{self.t.render(from_port)}-{self.t.render(to_port)}"
        if protocol == "-1":
            protocol = "all"

        source, source_kind = "", "unknown"
        if "CidrIp" in rule:
            source, source_kind = self.t.render(rule["CidrIp"]), "cidr"
        elif "CidrIpv6" in rule:
            source, source_kind = self.t.render(rule["CidrIpv6"]), "cidr"
        elif "SourceSecurityGroupId" in rule:
            refs = sorted(self.t.refs_in(rule["SourceSecurityGroupId"]))
            source = refs[0] if refs else self.t.render(rule["SourceSecurityGroupId"])
            source_kind = "sg"
        elif "SourcePrefixListId" in rule:
            source, source_kind = self.t.render(rule["SourcePrefixListId"]), "prefix-list"

        return {
            "source": source,
            "source_kind": source_kind,
            "protocol": protocol or "tcp",
            "ports": ports,
            "description": self.t.render(rule.get("Description")),
        }

    def _sg_attachments(self) -> dict[str, list[str]]:
        attachments: dict[str, list[str]] = defaultdict(list)
        for logical_id in sorted(self.t.resources):
            if self.type_of(logical_id) == "AWS::EC2::SecurityGroup":
                continue
            body = self.body(logical_id)
            for sg in sorted(self._sg_refs(body)):
                attachments[sg].append(logical_id)
        return attachments

    def _sg_refs(self, node: Any) -> set[str]:
        found: set[str] = set()
        if isinstance(node, dict):
            for key, value in node.items():
                if key in SG_PROPERTY_NAMES:
                    found |= {r for r in self.t.refs_in(value)
                              if self.type_of(r) == "AWS::EC2::SecurityGroup"}
                else:
                    found |= self._sg_refs(value)
        elif isinstance(node, list):
            for item in node:
                found |= self._sg_refs(item)
        return found

    def _listener(self, logical_id: str) -> dict:
        props = self.props(logical_id)
        lb_refs = sorted(self.t.refs_in(props.get("LoadBalancerArn")))
        return {
            "id": logical_id,
            "load_balancer": lb_refs[0] if lb_refs else "",
            "port": self.t.render(props.get("Port")),
            "protocol": self.t.render(props.get("Protocol")),
            "has_certificate": bool(props.get("Certificates")),
        }

    # -- derived views ----------------------------------------------------- #

    def routes_for(self, route_table: str) -> list[dict]:
        return [r for r in self.routes if r["route_table"] == route_table]

    def default_routes_for_subnet(self, subnet_id: str) -> list[dict]:
        rt = self.subnet_rt.get(subnet_id)
        if not rt:
            return []
        return [r for r in self.routes_for(rt) if r["destination"] in (OPEN_V4, OPEN_V6)]

    def _tier_order(self) -> dict[str, int]:
        preferred = ["public", "edge", "dmz", "application", "app", "private", "data", "database"]
        order = {tier: i for i, tier in enumerate(preferred)}
        extras = sorted({s["tier"] for s in self.subnets.values()} - set(order))
        for i, tier in enumerate(extras):
            order[tier] = len(preferred) + i
        return order


