class CfnLoader(yaml.SafeLoader):
    """SafeLoader that understands CloudFormation short-form intrinsics."""


def _cfn_multi_constructor(loader: CfnLoader, tag_suffix: str, node: yaml.Node) -> dict:
    key = "Ref" if tag_suffix == "Ref" else f"Fn::{tag_suffix}"
    if isinstance(node, yaml.ScalarNode):
        value: Any = loader.construct_scalar(node)
        if key == "Fn::GetAtt" and isinstance(value, str):
            value = value.split(".")
    elif isinstance(node, yaml.SequenceNode):
        value = loader.construct_sequence(node, deep=True)
    else:
        value = loader.construct_mapping(node, deep=True)
    return {key: value}


CfnLoader.add_multi_constructor("!", _cfn_multi_constructor)


