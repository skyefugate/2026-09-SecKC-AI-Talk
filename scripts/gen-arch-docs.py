def md_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_None._"]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        cells = [str(c).replace("|", "\\|") if str(c) else "—" for c in row]
        out.append("| " + " | ".join(cells) + " |")
    return out


def mermaid_block(title: str, lines: list[str]) -> list[str]:
    if not lines:
        return []
    return [f"### {title}", "", "```mermaid", *lines, "```", ""]


def build_index(root: Path, entries: list[dict]) -> str:
    """An index at the IaC root listing every documented stack."""
    lines = [
        "# Infrastructure as code",
        "",
        GENERATED_MARKER,
        "",
        "One directory per stack. Each `README.md` below is regenerated from its "
        "template on every push — see "
        "[`.github/workflows/architecture-docs.yml`](../.github/workflows/architecture-docs.yml).",
        "",
    ]
    rows = [
        [
            f'[`{e["dir"]}`](./{e["dir"]}/)',
            f'[architecture](./{e["dir"]}/README.md)',
            f'[`{e["template"]}`](./{e["dir"]}/{e["template"]})',
            str(e["resources"]),
            e["summary"],
        ]
        for e in entries
    ]
    lines += md_table(["Stack", "Docs", "Template", "Resources", "Summary"], rows)
    lines += [""]
    return "\n".join(lines).rstrip() + "\n"


def build_readme(template: Template, model: Model) -> tuple[str, list[str]]:
    t = template
    stack_title = t.path.parent.name.replace("-", " ").replace("_", " ").title()

    net = network_diagram(model)
    sec = security_diagram(model)
    comp = component_diagram(model)

    problems = (
        lint_mermaid(net, "network diagram")
        + lint_mermaid(sec, "security diagram")
        + lint_mermaid(comp, "component diagram")
    )

    lines: list[str] = [
        f"# {stack_title} — Architecture",
        "",
        GENERATED_MARKER,
        "",
        f"Generated from [`{t.path.name}`](./{t.path.name}) by "
        "[`scripts/gen-arch-docs.py`](../../scripts/gen-arch-docs.py). "
        "Edits here are overwritten on the next push — change the template instead.",
        "",
    ]

    if t.description:
        lines += [*t.description_blockquote(), ""]

    # At a glance
    vpc_id = model.vpcs[0] if model.vpcs else None
    glance = [
        ["Resources", str(len(t.resources))],
        ["Resource types", str(len(model.by_type))],
        ["Availability zones", str(len({s["az"] for s in model.subnets.values()}))],
        ["Subnets", str(len(model.subnets))],
        ["Tiers", ", ".join(sorted({s["tier"] for s in model.subnets.values()})) or "—"],
        ["Address family", "dual-stack (IPv4 + IPv6)" if model.has_ipv6 else "IPv4 only"],
    ]
    if vpc_id:
        glance.insert(0, ["VPC CIDR", t.render(model.props(vpc_id).get("CidrBlock"))])
    glance += [
        ["Security groups", str(len(model.security_groups))],
        ["Parameters", str(len(t.parameters))],
        ["Outputs", str(len(t.outputs))],
    ]
    lines += ["## At a glance", "", *md_table(["Property", "Value"], glance), ""]

    # Diagrams
    lines += ["## Diagrams", ""]
    lines += mermaid_block("Network topology and egress paths", net)
    lines += mermaid_block("Security group reachability", sec)
    lines += mermaid_block("Component dependencies", comp)
    if comp:
        lines += [
            "Arrows point from a resource to the resources it references. Red cylinders hold state; "
            "dashed borders are conditional resources.",
            "",
        ]

    # Addressing
    tier_order = model._tier_order()
    subnet_rows = []
    for subnet in sorted(
        model.subnets.values(), key=lambda s: (tier_order.get(s["tier"], 99), s["az"], s["name"])
    ):
        rt = model.subnet_rt.get(subnet["id"], "")
        defaults = model.default_routes_for_subnet(subnet["id"])
        default_desc = (
            ", ".join(f'{d["destination"]} → {d["target"]}' for d in defaults) if defaults else "none (isolated)"
        )
        subnet_rows.append(
            [
                f'`{subnet["name"]}`',
                subnet["tier"],
                subnet["az"],
                f'`{subnet["cidr"]}`',
                "yes" if subnet["public_ip_on_launch"] else "no",
                f"`{rt}`" if rt else "unassociated",
                default_desc,
            ]
        )
    lines += [
        "## Addressing",
        "",
        *md_table(
            ["Subnet", "Tier", "AZ", "CIDR", "Auto public IP", "Route table", "Default route"],
            subnet_rows,
        ),
        "",
    ]

    # Routing
    route_rows = []
    for rt_id in sorted(model.route_tables):
        table_routes = model.routes_for(rt_id)
        attached = sorted(
            model.subnets[s]["name"] for s, r in model.subnet_rt.items() if r == rt_id and s in model.subnets
        )
        if not table_routes:
            route_rows.append([f"`{rt_id}`", "—", "—", "local only", ", ".join(attached) or "—"])
            continue
        for route in sorted(table_routes, key=lambda r: (r["destination"], r["target"])):
            route_rows.append(
                [
                    f"`{rt_id}`",
                    f'`{route["destination"]}`',
                    f'`{route["target"]}`',
                    route["target_kind"].replace("Id", "") or "—",
                    ", ".join(attached) or "—",
                ]
            )
    lines += [
        "## Routing",
        "",
        *md_table(["Route table", "Destination", "Target", "Target kind", "Associated subnets"], route_rows),
        "",
    ]

    if model.endpoints:
        endpoint_rows = [
            [
                f'`{e["id"]}`',
                f'`{e["service"]}`',
                e["kind"],
                ", ".join(f"`{r}`" for r in e["route_tables"]) or "—",
                ", ".join(f"`{s}`" for s in e["subnets"]) or "—",
            ]
            for e in model.endpoints
        ]
        lines += [
            "### VPC endpoints",
            "",
            *md_table(["Endpoint", "Service", "Type", "Route tables", "Subnets"], endpoint_rows),
            "",
        ]

    # Security groups
    sg_rows = []
    for sg_id, sg in sorted(model.security_groups.items()):
        attached = ", ".join(f"`{a}`" for a in model.sg_attachments.get(sg_id, [])) or "—"
        if not sg["ingress"]:
            sg_rows.append([f'`{sg["name"]}`', "no ingress", "—", "—", attached])
            continue
        for rule in sg["ingress"]:
            source = rule["source"]
            if rule["source_kind"] == "sg" and source in model.security_groups:
                source = model.security_groups[source]["name"]
            sg_rows.append(
                [
                    f'`{sg["name"]}`',
                    f"`{source}`",
                    f'{rule["protocol"]}/{rule["ports"]}',
                    rule["description"] or "—",
                    attached,
                ]
            )
    lines += [
        "## Security groups",
        "",
        *md_table(["Group", "Ingress source", "Protocol/port", "Description", "Attached to"], sg_rows),
        "",
    ]

    # Parameters
    param_rows = []
    for name, spec in t.parameters.items():
        spec = spec or {}
        allowed = spec.get("AllowedValues")
        constraint = ", ".join(f"`{a}`" for a in allowed) if allowed else spec.get("AllowedPattern", "")
        param_rows.append(
            [
                f"`{name}`",
                str(spec.get("Type", "String")),
                f'`{spec.get("Default")}`' if "Default" in spec else "_required_",
                f"`{constraint}`" if constraint and not allowed else (constraint or "—"),
                str(spec.get("Description", "")).strip().replace("\n", " "),
            ]
        )
    lines += ["## Parameters", "", *md_table(["Name", "Type", "Default", "Constraint", "Description"], param_rows), ""]

    if t.conditions:
        cond_rows = []
        for name, expr in t.conditions.items():
            result = t.eval_condition(name)
            cond_rows.append(
                [
                    f"`{name}`",
                    f"`{t.render_expr(expr)}`",
                    {True: "true", False: "false", None: "undetermined"}[result],
                    ", ".join(
                        f"`{r}`"
                        for r in sorted(t.resources)
                        if model.condition_of(r) == name
                    ) or "—",
                ]
            )
        lines += [
            "## Conditions",
            "",
            *md_table(["Condition", "Expression", "With parameter defaults", "Controls"], cond_rows),
            "",
        ]

    # Outputs
    def output_value(spec: dict) -> str:
        value = (spec or {}).get("Value")
        if isinstance(value, dict) and "Ref" in value and value["Ref"] in t.resources:
            return f'id of `{value["Ref"]}`'
        return f"`{t.render(value)}`"

    output_rows = [
        [
            f"`{name}`",
            str((spec or {}).get("Description", "")).strip().replace("\n", " "),
            output_value(spec),
            f'`{t.render((spec or {}).get("Export", {}).get("Name"))}`' if (spec or {}).get("Export") else "—",
        ]
        for name, spec in t.outputs.items()
    ]
    lines += ["## Outputs", "", *md_table(["Output", "Description", "Value", "Export"], output_rows), ""]

    # Observations
    lines += ["## Observations", ""]
    lines += [f"- {note}" for note in observations(model)]
    lines += [""]

    # Inventory
    inventory_rows = [
        [f"`{rtype}`", str(len(ids)), ", ".join(f"`{i}`" for i in ids)]
        for rtype, ids in sorted(model.by_type.items())
    ]
    lines += [
        "## Resource inventory",
        "",
        *md_table(["Type", "Count", "Logical IDs"], inventory_rows),
        "",
        "---",
        "",
        "## How this file stays current",
        "",
        "A GitHub Actions workflow (`.github/workflows/architecture-docs.yml`) runs the generator on "
        "every push that touches the IaC, then commits the result. The document is a deterministic "
        "function of the template — no timestamps — so a run only produces a commit when the "
        "architecture genuinely changed.",
        "",
        f"Source template SHA-256: `{t.sha256}`",
        "",
    ]

    body = "\n".join(lines).rstrip() + "\n"
    body = re.sub(r"\n{3,}", "\n\n", body)
    return body, problems


