def find_templates(root: Path) -> list[Path]:
    found = [p for p in sorted(root.rglob("template.yaml"))]
    found += [p for p in sorted(root.rglob("template.yml"))]
    return sorted(set(found))


def is_tracked_by_git(path: Path) -> bool:
    """True if git knows about ``path``, even when it is absent from the worktree."""
    try:
        result = subprocess.run(
            ["git", "ls-files", "--error-unmatch", "--", str(path)],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def sync_file(path: Path, content: str, check: bool, report: dict) -> None:
    """Write ``content`` to ``path``, or record staleness in ``--check`` mode."""
    existing = path.read_text() if path.exists() else None

    if existing == content:
        report["unchanged"] += 1
        print(f"unchanged  {path}")
        return

    if check:
        report["stale"].append(str(path))
        print(f"STALE      {path}")
        sys.stdout.writelines(
            difflib.unified_diff(
                (existing or "").splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=f"{path} (committed)",
                tofile=f"{path} (regenerated)",
            )
        )
        return

    if existing is not None and GENERATED_MARKER not in existing:
        raise RuntimeError(
            f"{path} exists but is not generator-owned (marker missing). "
            "Refusing to overwrite hand-written documentation."
        )
    if existing is None and is_tracked_by_git(path):
        # Tracked but absent from the worktree: someone deleted it locally. Writing
        # here would silently replace committed content that we never got to inspect.
        raise RuntimeError(
            f"{path} is tracked by git but missing from the working tree. "
            f"Restore it first (git checkout -- {path}) so its contents can be checked, "
            "or delete it from git if it is meant to be generated."
        )
    path.write_text(content)
    report["written"] += 1
    print(f"{'updated' if existing else 'created'}    {path}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="iac", help="directory to scan for templates (default: iac)")
    parser.add_argument("--check", action="store_true", help="exit non-zero if any README is stale")
    parser.add_argument(
        "--index",
        action="store_true",
        help="also write an index at the IaC root (off by default: that file is usually hand-written)",
    )
    args = parser.parse_args(argv)

    root = Path(args.root)
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        return 2

    templates = find_templates(root)
    if not templates:
        print(f"error: no template.y[a]ml found under {root}", file=sys.stderr)
        return 2

    report: dict = {"written": 0, "unchanged": 0, "stale": []}
    all_problems: list[str] = []
    entries: list[dict] = []

    try:
        for template_path in templates:
            template = Template(template_path)
            model = Model(template)
            content, problems = build_readme(template, model)
            all_problems += [f"{template_path}: {p}" for p in problems]

            summary = template.description.split("\n")[0].strip() if template.description else ""
            entries.append(
                {
                    "dir": template_path.parent.relative_to(root).as_posix(),
                    "template": template_path.name,
                    "resources": len(template.resources),
                    "summary": summary,
                }
            )
            sync_file(template_path.parent / "README.md", content, args.check, report)

        if args.index and entries:
            sync_file(root / "README.md", build_index(root, entries), args.check, report)
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if all_problems:
        print("\nMermaid structural problems:", file=sys.stderr)
        for problem in all_problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    if args.check and report["stale"]:
        print(
            "\nArchitecture docs are out of date. Run:\n"
            f"    python3 scripts/gen-arch-docs.py --root {root}\n"
            "and commit the result.",
            file=sys.stderr,
        )
        return 1

    print(f"\ndone: {report['written']} written, {report['unchanged']} already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
