PSEUDO_PARAMS = {
    "AWS::Region": "<region>",
    "AWS::AccountId": "<account-id>",
    "AWS::Partition": "aws",
    "AWS::StackName": "<stack-name>",
    "AWS::URLSuffix": "amazonaws.com",
    "AWS::NoValue": "",
}


class Template:
    """A parsed template plus helpers for resolving intrinsics to readable text."""

    def __init__(self, path: Path):
        self.path = path
        self.raw_bytes = path.read_bytes()
        self.doc: dict = yaml.load(self.raw_bytes, Loader=CfnLoader) or {}
        self.parameters: dict = self.doc.get("Parameters") or {}
        self.mappings: dict = self.doc.get("Mappings") or {}
        self.conditions: dict = self.doc.get("Conditions") or {}
        self.resources: dict = self.doc.get("Resources") or {}
        self.outputs: dict = self.doc.get("Outputs") or {}
        self.description: str = str(self.doc.get("Description") or "").strip()

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.raw_bytes).hexdigest()

    def param_default(self, name: str) -> str | None:
        param = self.parameters.get(name)
        if not isinstance(param, dict) or "Default" not in param:
            return None
        return str(param["Default"])

    def render(self, value: Any) -> str:
        """Best-effort human-readable rendering of a property value."""
        if value is None:
            return ""
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, (int, float, str)):
            return str(value)
        if isinstance(value, list):
            return ", ".join(self.render(item) for item in value)
        if not isinstance(value, dict):
            return str(value)

        if "Ref" in value:
            target = value["Ref"]
            if target in PSEUDO_PARAMS:
                return PSEUDO_PARAMS[target]
            default = self.param_default(target)
            return default if default is not None else str(target)

        for key, raw in value.items():
            if key == "Fn::Sub":
                return self._render_sub(raw)
            if key == "Fn::GetAtt":
                parts = raw if isinstance(raw, list) else str(raw).split(".")
                return ".".join(str(p) for p in parts)
            if key == "Fn::FindInMap":
                return self._render_find_in_map(raw)
            if key == "Fn::Select":
                return self._render_select(raw)
            if key == "Fn::GetAZs":
                return "AZs in region"
            if key == "Fn::Join":
                delim, items = raw[0], raw[1]
                return str(delim).join(self.render(i) for i in items)
            if key == "Fn::If":
                cond, when_true, when_false = raw
                return f"if {cond}: {self.render(when_true)} else {self.render(when_false)}"
            if key == "Fn::Equals":
                return f"{self.render(raw[0])} == {self.render(raw[1])}"
            if key == "Fn::Not":
                return f"not ({self.render(raw[0])})"
            if key == "Fn::And":
                return " and ".join(f"({self.render(i)})" for i in raw)
            if key == "Fn::Or":
                return " or ".join(f"({self.render(i)})" for i in raw)
            if key == "Fn::ImportValue":
                return f"import {self.render(raw)}"
            if key == "Condition":
                return f"condition {raw}"
        # Unknown structure: render deterministically rather than guessing.
        return ", ".join(f"{k}={self.render(v)}" for k, v in sorted(value.items()))

    def _render_sub(self, raw: Any) -> str:
        if isinstance(raw, list):
            body, local_vars = str(raw[0]), raw[1] or {}
        else:
            body, local_vars = str(raw), {}

        def substitute(match: re.Match[str]) -> str:
            name = match.group(1)
            if name in local_vars:
                return self.render(local_vars[name])
            if name in PSEUDO_PARAMS:
                return PSEUDO_PARAMS[name]
            default = self.param_default(name)
            if default is not None:
                return default
            if "." in name:  # GetAtt form inside Sub
                return name
            return f"<{name}>"

        return re.sub(r"\$\{([^}]+)\}", substitute, body)

    def _render_find_in_map(self, raw: Any) -> str:
        try:
            map_name, top, second = (self.render(part) for part in raw[:3])
            return str(self.mappings[map_name][top][second])
        except Exception:
            return "|".join(self.render(part) for part in raw)

    def _render_select(self, raw: Any) -> str:
        index_raw, source = raw[0], raw[1]
        try:
            index = int(self.render(index_raw))
        except (TypeError, ValueError):
            return f"select {self.render(index_raw)} of {self.render(source)}"
        if isinstance(source, dict) and "Fn::GetAZs" in source:
            return az_letter(index)
        if isinstance(source, list):
            return self.render(source[index])
        return f"select {index} of {self.render(source)}"

    def az_index(self, value: Any) -> int | None:
        """Extract the AZ index from ``!Select [n, !GetAZs ""]``."""
        if isinstance(value, dict) and "Fn::Select" in value:
            index_raw, source = value["Fn::Select"][0], value["Fn::Select"][1]
            if isinstance(source, dict) and "Fn::GetAZs" in source:
                try:
                    return int(self.render(index_raw))
                except (TypeError, ValueError):
                    return None
        return None

    def refs_in(self, value: Any) -> set[str]:
        """Every logical resource id referenced anywhere inside ``value``."""
        found: set[str] = set()
        if isinstance(value, dict):
            for key, raw in value.items():
                if key == "Ref" and isinstance(raw, str) and raw in self.resources:
                    found.add(raw)
                elif key == "Fn::GetAtt":
                    parts = raw if isinstance(raw, list) else str(raw).split(".")
                    if parts and str(parts[0]) in self.resources:
                        found.add(str(parts[0]))
                else:
                    found |= self.refs_in(raw)
        elif isinstance(value, list):
            for item in value:
                found |= self.refs_in(item)
        return found


    # -- conditions -------------------------------------------------------- #

    def render_expr(self, value: Any) -> str:
        """Like ``render`` but keeps parameter names instead of substituting defaults.

        Used for conditions, where ``EnableReadReplica == "true"`` is informative and
        ``true == true`` is not.
        """
        if isinstance(value, dict):
            if "Ref" in value:
                target = value["Ref"]
                return PSEUDO_PARAMS.get(target, str(target))
            for key, raw in value.items():
                if key == "Fn::Equals":
                    return f"{self.render_expr(raw[0])} == {self.render_expr(raw[1])}"
                if key == "Fn::Not":
                    return f"not ({self.render_expr(raw[0])})"
                if key == "Fn::And":
                    return " and ".join(f"({self.render_expr(i)})" for i in raw)
                if key == "Fn::Or":
                    return " or ".join(f"({self.render_expr(i)})" for i in raw)
                if key == "Condition":
                    return str(raw)
        if isinstance(value, str):
            return f'"{value}"' if not value.startswith("$") else value
        return self.render(value)

    def eval_condition(self, name: str, seen: frozenset[str] = frozenset()) -> bool | None:
        """Evaluate a condition using parameter defaults. ``None`` when undecidable."""
        if name in seen or name not in self.conditions:
            return None
        return self._eval(self.conditions[name], seen | {name})

    def _eval(self, expr: Any, seen: frozenset[str]) -> bool | None:
        if isinstance(expr, bool):
            return expr
        if not isinstance(expr, dict):
            return None
        for key, raw in expr.items():
            if key == "Fn::Equals":
                left, right = self.render(raw[0]), self.render(raw[1])
                return left == right
            if key == "Fn::Not":
                inner = self._eval(raw[0], seen)
                return None if inner is None else not inner
            if key == "Fn::And":
                results = [self._eval(i, seen) for i in raw]
                return None if None in results else all(results)
            if key == "Fn::Or":
                results = [self._eval(i, seen) for i in raw]
                return None if None in results else any(results)
            if key == "Condition":
                return self.eval_condition(str(raw), seen)
        return None

    def description_blockquote(self) -> list[str]:
        """Render the template Description as a Markdown blockquote, paragraphs intact."""
        if not self.description:
            return []
        paragraphs = [p.strip() for p in self.description.split("\n") if p.strip()]
        out: list[str] = []
        for i, paragraph in enumerate(paragraphs):
            if i:
                out.append(">")
            out.append(f"> {paragraph}")
        return out


def az_letter(index: int) -> str:
    return chr(ord("a") + index) if 0 <= index < 26 else str(index)


