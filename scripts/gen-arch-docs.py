#!/usr/bin/env python3
"""Generate living architecture documentation from CloudFormation templates.

For every directory under the IaC root that contains a ``template.yaml`` (or
``template.yml``), this writes a ``README.md`` next to it containing Mermaid
diagrams and reference tables derived straight from the template.

The output is a pure function of the template: no timestamps, no commit SHAs,
nothing that changes between runs. That means CI can regenerate on every push
and only produce a commit when the architecture actually changed.

Usage
-----
    python3 scripts/gen-arch-docs.py                 # write docs
    python3 scripts/gen-arch-docs.py --check         # fail if docs are stale
    python3 scripts/gen-arch-docs.py --root iac      # override the IaC root
    python3 scripts/gen-arch-docs.py --index         # also write an index at the root

Generated files are marked, and the generator refuses to overwrite anything that
lacks the marker or that git tracks but the worktree is missing.
"""

