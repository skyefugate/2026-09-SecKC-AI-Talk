def observations(model: Model) -> list[str]:
    notes: list[str] = []
    t = model.t

    az_count = len({s["az"] for s in model.subnets.values()})
    nat_ids = model.by_type.get("AWS::EC2::NatGateway", [])
    nat_dependent_tables = {
        r["route_table"] for r in model.routes if r["target_kind"] == "NatGatewayId"
    }
    nat_dependent_subnets = sorted(
        s for s, rt in model.subnet_rt.items() if rt in nat_dependent_tables
    )
    if len(nat_ids) == 1 and len(nat_dependent_subnets) > 1:
        nat_az = ""
        placed_in = sorted(t.refs_in(model.props(nat_ids[0]).get("SubnetId")))
        if placed_in and placed_in[0] in model.subnets:
            nat_az = f' in AZ {model.subnets[placed_in[0]]["az"]}'
        notes.append(
            f"**Single NAT gateway.** `{nat_ids[0]}`{nat_az} carries IPv4 egress for "
            f"{len(nat_dependent_subnets)} subnets across {az_count} AZs. Losing that AZ removes "
            "outbound IPv4 for the whole tier. One NAT per AZ is the fix; cost is the trade."
        )
    elif 1 < len(nat_ids) < az_count and nat_dependent_subnets:
        notes.append(
            f"**Partial NAT redundancy.** {len(nat_ids)} NAT gateways for {az_count} AZs — "
            "at least one AZ borrows egress from another."
        )

    isolated = sorted(
        model.subnets[s]["name"]
        for s, rt in model.subnet_rt.items()
        if not model.routes_for(rt) and s in model.subnets
    )
    if isolated:
        notes.append(
            "**Isolated subnets have no route table entries at all**: "
            + ", ".join(f"`{n}`" for n in isolated)
            + ". No egress path exists, which is the correct posture for a data tier."
        )

    world_open: list[str] = []
    for sg_id, sg in sorted(model.security_groups.items()):
        for rule in sg["ingress"]:
            if rule["source"] in (OPEN_V4, OPEN_V6):
                world_open.append(
                    f'`{sg["name"]}` accepts {rule["protocol"]}/{rule["ports"]} from `{rule["source"]}`'
                )
    if world_open:
        notes.append("**Internet-reachable ingress**: " + "; ".join(world_open) + ".")

    plaintext = [
        f'`{l["id"]}` on port {l["port"]} ({l["protocol"]})'
        for l in model.listeners
        if l["protocol"].upper() in {"HTTP", "TCP"} and not l["has_certificate"]
    ]
    if plaintext:
        notes.append(
            "**Listener without TLS termination**: "
            + ", ".join(plaintext)
            + ". Traffic between client and load balancer is unencrypted."
        )

    gateway_endpoints = [e for e in model.endpoints if e["kind"].lower() == "gateway"]
    if gateway_endpoints and model.has_ipv6:
        services = ", ".join(f'`{e["service"]}`' for e in gateway_endpoints)
        notes.append(
            f"**IPv4/IPv6 asymmetry.** Gateway endpoints ({services}) are IPv4-only, while the VPC "
            "has IPv6 and an egress-only IGW. IPv6-only clients cannot use those endpoints."
        )

    risky_stateful: list[str] = []
    for rtype in sorted(STATEFUL_TYPES):
        for logical_id in model.by_type.get(rtype, []):
            policy = str(model.body(logical_id).get("DeletionPolicy", "Delete (default)"))
            if policy.startswith("Delete"):
                risky_stateful.append(f"`{logical_id}` → `{policy}`")
    if risky_stateful:
        notes.append(
            "**Stateful resources that will be destroyed on stack delete**: "
            + ", ".join(risky_stateful)
            + ". Confirm that is intentional."
        )

    unencrypted: list[str] = []
    for logical_id in model.by_type.get("AWS::RDS::DBInstance", []):
        props = model.props(logical_id)
        if "SourceDBInstanceIdentifier" in props:
            continue  # replicas inherit encryption from the source
        if not props.get("StorageEncrypted"):
            unencrypted.append(f"`{logical_id}`")
    if unencrypted:
        notes.append("**Storage encryption not enabled**: " + ", ".join(unencrypted) + ".")

    conditional = [
        (logical_id, model.condition_of(logical_id))
        for logical_id in sorted(model.t.resources)
        if model.condition_of(logical_id)
    ]
    if conditional:
        rendered = ", ".join(f"`{r}` (`{c}`)" for r, c in conditional)
        notes.append(
            f"**Conditional resources — the blast-radius toggles**: {rendered}. "
            "Flipping the controlling parameter adds or removes these on the next deploy."
        )

    single_az_stateful: list[str] = []
    for logical_id in model.by_type.get("AWS::RDS::DBInstance", []):
        props = model.props(logical_id)
        if "SourceDBInstanceIdentifier" in props:
            continue
        if not props.get("MultiAZ"):
            single_az_stateful.append(f"`{logical_id}`")
    if single_az_stateful:
        notes.append("**Single-AZ database**: " + ", ".join(single_az_stateful) + ".")

    no_retention = [
        f"`{lg}`"
        for lg in model.by_type.get("AWS::Logs::LogGroup", [])
        if "RetentionInDays" not in model.props(lg)
    ]
    if no_retention:
        notes.append(
            "**Log groups retain forever**: " + ", ".join(no_retention) + ". Cost grows without bound."
        )

    if not notes:
        notes.append("No structural observations were triggered by the current checks.")
    return notes


